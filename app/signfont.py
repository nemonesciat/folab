"""FOLab's own sign alphabet: capitals, figures and a few marks drawn as pen paths (the middle of each stroke), cap height
10, y down (0 the top, 10 the baseline), each glyph its own width. signpaint draws these paths as a neon bender, a
sign-writer or a carver would.

Proportions after the period's signs: round letters (O C G Q D) nearly as wide as tall, narrow ones (E F L S) about half,
M and W widest. `glyphs(waist)` sets where the crossbars of A E F H sit (0.5 the middle; deco faces put them high,
about 0.4, the period's mark). Curves are sampled as polylines fine enough that no corner shows at sign sizes."""
import math

CAP = 10.0
STEPS = 18                 # points a quarter circle


def arc(cx, cy, rx, ry, a0, a1):
    """Points along an ellipse from angle a0 to a1 (degrees; 0 to the right, 90 down, as the picture's y runs)."""
    n = max(2, int(abs(a1 - a0) / 90.0 * STEPS) + 1)
    return [(cx + rx * math.cos(math.radians(a0 + (a1 - a0) * k / (n - 1))), cy + ry * math.sin(math.radians(a0 + (a1 - a0) * k / (n - 1))))
            for k in range(n)]


