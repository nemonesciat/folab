def sub(tag, data):
    return struct.pack('<4sH', tag.encode(), len(data)) + data


def plugin(folder, name, masters=(), edid=None, formid=None, esm=False):
    os.makedirs(folder, exist_ok=True)
    head = sub('HEDR', struct.pack('<fiI', 1.34, 1, 0x900)) + sub('CNAM', b'test\0')
    for m in masters:
        head += sub('MAST', m.encode() + b'\0') + sub('DATA', b'\0' * 8)
    tree = plugintree.Plugin.empty(head, 1 if esm else 0)
    low = formid if formid is not None else (len(masters) << 24) | 0x800
    tree.top('MISC').kids.append(plugintree.Rec.new('MISC', 0, low, sub('EDID', edid.encode() + b'\0') + sub('FULL', (edid + ' name').encode() + b'\0')))
    with open(os.path.join(folder, name), 'wb') as f:
        f.write(tree.bytes())


def text(path, body):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8', newline='\r\n') as f:
        f.write(body)


