def tree_hash():
    h = {}
    for d, _s, files in os.walk(MODS):
        for fn in files:
            with open(os.path.join(d, fn), 'rb') as f:
                h[os.path.join(d, fn)] = hashlib.sha1(f.read()).hexdigest()
    return h


