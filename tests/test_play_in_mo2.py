class FakeVirtual:
    """MO2's virtual folder as a program it started sees it: the loadout's files, and new ones land in overwrite."""
    def exists(self, lo, rel):
        return bool(lo.path(rel)) or os.path.exists(os.path.join(OVER, rel))

    def create(self, lo, rel, src):
        real = os.path.join(OVER, rel)
        os.makedirs(os.path.dirname(real), exist_ok=True)
        shutil.copyfile(src, real)
        return real

    def remove(self, lo, rel, real):
        os.remove(real)


