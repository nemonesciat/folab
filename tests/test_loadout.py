def everything():
    out = {}
    for root in (INST, GAME):
        for d, _dirs, files in os.walk(root):
            for fn in files:
                p = os.path.join(d, fn)
                with open(p, 'rb') as f:
                    out[p] = (hashlib.sha1(f.read()).hexdigest(), os.path.getmtime(p))
    return out


